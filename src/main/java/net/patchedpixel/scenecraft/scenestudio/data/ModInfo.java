package net.patchedpixel.scenecraft.scenestudio.data;

import java.util.Objects;

public class ModInfo {
    private final String id;
    private final String name;
    private final String version;

    public ModInfo(String id, String name, String version) {
        this.id = id;
        this.name = name;
        this.version = version;
    }

    public String getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getVersion() {
        return version;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof ModInfo)) return false;
        ModInfo that = (ModInfo) o;
        return Objects.equals(id, that.id) && Objects.equals(name, that.name) && Objects.equals(version, that.version);
    }

    @Override
    public int hashCode() {
        return Objects.hash(id, name, version);
    }

    @Override
    public String toString() {
        return "ModInfo(id=" + id + ", name=" + name + ", version=" + version + ")";
    }
}
